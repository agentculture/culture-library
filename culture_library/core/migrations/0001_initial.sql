-- feed.py. SQLite's column "cursor" is "seq" here: CURSOR is an SQL keyword, and a name that
-- never needs quoting keeps every query plain. The API still calls it cursor (SELECT seq AS
-- cursor). Ordering under concurrent writers is the feed port's job (spec: serialised appends).
CREATE TABLE feed (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL,
    item_id bigint NOT NULL,
    sha256 text NOT NULL,
    kind text NOT NULL,
    visibility text NOT NULL DEFAULT 'private',
    at text NOT NULL,
    data jsonb,
    subject text NOT NULL DEFAULT 'item'
);
CREATE INDEX feed_item_id ON feed (item_id);

