-- The initial library schema. Until the first Postgres release ships, this file is still
-- being written: t1 put the items table here (core/store.py's own CRUD); t4 adds every other
-- table. After that release, a schema change is a new NNNN_*.sql file, never an edit here.
--
-- Timestamps stay TEXT ISO-8601 (as on SQLite), so Item and the API keep their shapes.
-- The kind CHECK must name exactly culture_library.core.models.KINDS, in order
-- (tests/core/test_store_pg.py::test_items_kind_check_matches_kinds); adding a kind is a new
-- migration that drops and re-adds items_kind_check.
CREATE TABLE items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256 text NOT NULL UNIQUE,
    kind text NOT NULL CONSTRAINT items_kind_check CHECK (kind IN (
        'book', 'article', 'newspaper', 'document', 'transcript', 'diary', 'spec', 'plan',
        'devague-record', 'todo', 'discord-message', 'design'
    )),
    title text NOT NULL,
    author text NOT NULL DEFAULT '',
    format text NOT NULL,
    size bigint NOT NULL,
    visibility text NOT NULL DEFAULT 'private'
        CONSTRAINT items_visibility_check CHECK (visibility IN ('private', 'public')),
    created_at text NOT NULL,
    archived_at text
);
