-- search.py: full text. SQLite kept it in the FTS5 tables search_fts (rowid = items.id;
-- title, body) and repodoc_fts (rowid = repodocs.id; title, body, label, visibility). Here the
-- text lives in one plain table per corpus, keyed by the owner's id and dropped with it, with
-- a generated tsvector: title weighted A, body weighted B, English stemming (the FTS5 tables
-- used porter). Keeping the text out of items/repodocs keeps those rows small and leaves the
-- "indexed or not" state where FTS5 had it: a row exists once the indexer wrote one.
-- As in FTS5, "title" is what search matches as the title (an item's "title author", a repo
-- doc's "title path"); repodoc_text.label is the display title, and visibility is a copy kept
-- in step by the indexer so a search filters without a join. Ranking (ts_rank, ts_headline)
-- is the search port's (t12).
CREATE TABLE item_text (
    item_id bigint PRIMARY KEY REFERENCES items (id) ON DELETE CASCADE,
    title text NOT NULL DEFAULT '',
    body text NOT NULL DEFAULT '',
    tsv tsvector GENERATED ALWAYS AS (library_fts_doc(title, body)) STORED
);
CREATE INDEX item_text_tsv ON item_text USING gin (tsv);

CREATE TABLE repodoc_text (
    doc_id bigint PRIMARY KEY REFERENCES repodocs (id) ON DELETE CASCADE,
    title text NOT NULL DEFAULT '',
    body text NOT NULL DEFAULT '',
    label text NOT NULL DEFAULT '',
    visibility text NOT NULL DEFAULT 'private'
        CONSTRAINT repodoc_text_visibility_check CHECK (library_valid_visibility(visibility)),
    tsv tsvector GENERATED ALWAYS AS (library_fts_doc(title, body)) STORED
);
CREATE INDEX repodoc_text_tsv ON repodoc_text USING gin (tsv);

-- search.py: vectors (decision c42). vec is a dimensionless pgvector "vector"; each row says
-- which model made it (model_id: the real model, e.g. google/embeddinggemma-2, not a gateway
-- role) and how (strategy: core/embedding_strategy.py's Strategy.key(), compact sorted JSON
-- compared as text: document and query prompts, chunker and max_chars, dimension,
-- normalisation). The pair is part of the key, so vectors of two strategies sit side by side.
-- SQLite's "model" label column ("gemma2-embed+Retrieval-document") is replaced by the pair.
-- A vector's length must equal its strategy's dimension.
-- Each (model_id, strategy) gets its own partial HNSW cosine index over vec cast to its
-- dimension, built by embedding_strategy.hnsw_index_sql(); the current pair's is created here
-- and the indexer (t13) creates the next one. A query uses it when it filters on the same
-- model_id and strategy and orders by vec::vector(N) <=> query::vector(N).
CREATE TABLE embeddings (
    item_id bigint NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    model_id text NOT NULL CONSTRAINT embeddings_model_id_check CHECK (model_id <> ''),
    strategy text NOT NULL,
    chunk_no integer NOT NULL,
    text text NOT NULL,
    vec vector NOT NULL,
    PRIMARY KEY (item_id, model_id, strategy, chunk_no),
    CONSTRAINT embeddings_dimension_check
        CHECK (vector_dims(vec) = (strategy::jsonb ->> 'dimension')::integer)
);
CREATE INDEX IF NOT EXISTS embeddings_hnsw_a5c403df5df1 ON embeddings
    USING hnsw ((vec::vector(768)) vector_cosine_ops)
    WHERE model_id = 'google/embeddinggemma-2'
    AND strategy = '{"chunker":"paragraph-pack","dimension":768,"document_prompt":"Retrieval-document","max_chars":1000,"normalisation":"l2","query_prompt":"Retrieval-query"}';

CREATE TABLE repodoc_embeddings (
    doc_id bigint NOT NULL REFERENCES repodocs (id) ON DELETE CASCADE,
    model_id text NOT NULL CONSTRAINT repodoc_embeddings_model_id_check CHECK (model_id <> ''),
    strategy text NOT NULL,
    chunk_no integer NOT NULL,
    text text NOT NULL,
    vec vector NOT NULL,
    PRIMARY KEY (doc_id, model_id, strategy, chunk_no),
    CONSTRAINT repodoc_embeddings_dimension_check
        CHECK (vector_dims(vec) = (strategy::jsonb ->> 'dimension')::integer)
);
CREATE INDEX IF NOT EXISTS repodoc_embeddings_hnsw_a5c403df5df1 ON repodoc_embeddings
    USING hnsw ((vec::vector(768)) vector_cosine_ops)
    WHERE model_id = 'google/embeddinggemma-2'
    AND strategy = '{"chunker":"paragraph-pack","dimension":768,"document_prompt":"Retrieval-document","max_chars":1000,"normalisation":"l2","query_prompt":"Retrieval-query"}';

-- eval_store.py
CREATE TABLE eval_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    item_sha256 text NOT NULL,
    chunker_json jsonb NOT NULL,
    adapter text NOT NULL,
    adapter_version text NOT NULL,
    generator_json jsonb NOT NULL,
    version integer NOT NULL DEFAULT 1,
    created_at text NOT NULL
);
CREATE INDEX eval_sets_item ON eval_sets (item_id);

CREATE TABLE eval_samples (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id bigint NOT NULL REFERENCES eval_sets (id) ON DELETE CASCADE,
    question text NOT NULL,
    reference_answer text NOT NULL,
    reference_chunk_shas jsonb NOT NULL DEFAULT '[]',
    reference_contexts jsonb NOT NULL DEFAULT '[]',
    source_urls jsonb NOT NULL DEFAULT '[]'
);
CREATE INDEX eval_samples_set ON eval_samples (set_id);

CREATE TABLE eval_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id bigint NOT NULL REFERENCES eval_sets (id) ON DELETE CASCADE,
    set_version integer NOT NULL DEFAULT 1,
    status text NOT NULL
        CONSTRAINT eval_runs_status_check CHECK (status IN ('complete', 'partial', 'failed')),
    config_json jsonb NOT NULL,
    total integer NOT NULL DEFAULT 0,
    completed integer NOT NULL DEFAULT 0,
    aggregates_json jsonb,
    created_at text NOT NULL,
    partial_aggregates_json jsonb,
    error_rate double precision,
    suites_json jsonb,
    running boolean NOT NULL DEFAULT false,
    CONSTRAINT eval_runs_aggregates_check CHECK (aggregates_json IS NULL OR status = 'complete')
);
CREATE INDEX eval_runs_set ON eval_runs (set_id);

-- sample_id carries no foreign key, as on SQLite: a run keeps its per-question snapshot.
CREATE TABLE eval_run_samples (
    run_id bigint NOT NULL REFERENCES eval_runs (id) ON DELETE CASCADE,
    sample_id bigint NOT NULL,
    retrieved_chunk_shas jsonb NOT NULL DEFAULT '[]',
    scores_json jsonb NOT NULL DEFAULT '{}',
    question text,
    reference_chunk_shas jsonb,
    set_version integer,
    retrieved_item_ids jsonb,
    latency_ms double precision,
    freshness jsonb,
    PRIMARY KEY (run_id, sample_id)
);
