-- The initial library schema: every table of the SQLite store (live 0.19.8), typed for
-- Postgres. t1 put the items table here (core/store.py's own CRUD) and t4 the rest. Until the
-- first Postgres release ships this file may still change; after it, a schema change is a new
-- NNNN_*.sql file, never an edit here.
--
-- Timestamps stay TEXT ISO-8601 (as on SQLite), so Item and the API keep their shapes.
-- The kind CHECK must name exactly culture_library.core.models.KINDS, in order
-- (tests/core/test_store_pg.py::test_items_kind_check_matches_kinds); adding a kind is a new
-- migration that drops and re-adds items_kind_check.
-- Shared CHECK and generated-column logic, defined once (IMMUTABLE so a generated column may
-- call it). library_fts_doc is replaced by migration 0002.
CREATE FUNCTION library_valid_visibility(v text) RETURNS boolean
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    AS $$ SELECT v IN ('private', 'public') $$;
CREATE FUNCTION library_valid_state(v text) RETURNS boolean
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    AS $$ SELECT v IN ('pending', 'done', 'failed') $$;
CREATE FUNCTION library_fts_doc(title text, body text) RETURNS tsvector
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    AS $$ SELECT setweight(to_tsvector('english'::regconfig, title), 'A')
        || setweight(to_tsvector('english'::regconfig, body), 'B') $$;

CREATE TABLE items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256 text NOT NULL UNIQUE,
    kind text NOT NULL CONSTRAINT items_kind_check CHECK (kind IN (
        'book', 'article', 'newspaper', 'document', 'transcript', 'diary', 'spec', 'plan',
        'devague-record', 'todo', 'discord-message', 'design'
    )),
    title text NOT NULL,
    author text NOT NULL DEFAULT '',
    format text NOT NULL,
    size bigint NOT NULL,
    visibility text NOT NULL DEFAULT 'private'
        CONSTRAINT items_visibility_check CHECK (library_valid_visibility(visibility)),
    created_at text NOT NULL,
    archived_at text
);

-- Conventions for every table below (ported from the SQLite schema of live 0.19.8, kept in
-- tests/migrate/fixtures/sqlite_schema_0.19.8.sql and checked by tests/core/test_schema_pg.py):
-- * A table's own id is "bigint GENERATED BY DEFAULT AS IDENTITY", so the one-shot copy (t14)
--   can insert the SQLite ids and then move each identity past the largest.
-- * Timestamps stay TEXT ISO-8601 strings, byte for byte; the indexer's epoch-second REAL
--   columns become double precision.
-- * INTEGER 0/1 flags become boolean (default false).
-- * JSON stored in TEXT becomes jsonb. Every reader json.loads these values and writers dump
--   with sort_keys, so no API returns the stored text verbatim. jsonb keeps no key order and
--   rejects NaN, Infinity and \u0000, all of which SQLite's TEXT accepted.
--   Kept as text on purpose: api_keys.scopes and api_keys.kinds (comma lists keys.py splits)
--   and index_meta.value (an opaque string).
-- * Foreign keys, CHECKs, UNIQUEs and the named indexes are the SQLite ones; no new foreign
--   key is added to a table that had none (feed.item_id outlives deleted items, for one).
-- * Triggers (the repodoc_dirty marks) arrive with the indexer port (t13), not here.

