-- keys.py
CREATE TABLE api_keys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    key_id text NOT NULL UNIQUE,
    key_hash text NOT NULL,
    scopes text NOT NULL,
    kinds text,
